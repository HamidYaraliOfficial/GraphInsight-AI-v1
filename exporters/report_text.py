def axis_range(ax, box: dict, orientation: str):
    """Data range spanned by the plot-area edges according to the calibration."""
    if ax is None or ax.calibration is None or not box:
        return None
    c = ax.calibration
    try:
        if orientation == "x":
            a, b = c.pixel_to_value([box["x0"], box["x1"]])
        else:
            a, b = c.pixel_to_value([box["y1"], box["y0"]])
        return float(a), float(b)
    except Exception:  # noqa: BLE001
        return None


def fnum(v, n: int = 5) -> str:
    if v is None:
        return "—"
    try:
        v = float(v)
    except (TypeError, ValueError):
        return str(v)
    return f"{v:.{n}g}"


def series_summary_rows(chart) -> list[dict]:
    rows = []
    an = (chart.analysis or {}).get("series", {})
    for s in chart.series:
        a = an.get(s.name) or {}
        ft = a.get("features") or {}
        p = s.points.dropna(subset=["x", "y"])
        row = dict(series=s.name, points=len(s.points))
        if len(p):
            ps = p.sort_values("x")
            row.update(start=f"({fnum(ps.x.iloc[0])}, {fnum(ps.y.iloc[0])})", end=f"({fnum(ps.x.iloc[-1])}, {fnum(ps.y.iloc[-1])})",
                       maximum=f"({fnum(ft.get('global_max', {}).get('x', ps.x[ps.y.idxmax()]))}, {fnum(p.y.max())})",
                       minimum=f"({fnum(ft.get('global_min', {}).get('x', ps.x[ps.y.idxmin()]))}, {fnum(p.y.min())})")
        row["confidence"] = fnum(s.confidence, 3)
        rows.append(row)
    return rows


def axis_table(chart, T: dict):
    """Header and rows describing the axes (title, unit, scale, range, calibration quality)."""
    header = [T["name"], T["chart_title"].replace(T["chart_title"], "title") if False else "title", T["unit"], T["scale"], T["rng"], "calibration"]
    rows = []
    for lab, ax, o in ((T["x_axis"], chart.x_axis, "x"), (T["y_axis"], chart.y_axis, "y"), (T["y2_axis"], chart.y2_axis, "y")):
        if ax is None:
            continue
        rg = axis_range(ax, chart.box, o)
        c = ax.calibration
        rows.append([lab, ax.title or T["unknown"], ax.unit or T["unknown"], c.scale if c else T["unknown"],
                     f"{fnum(rg[0], 4)} … {fnum(rg[1], 4)}" if rg else T["unknown"],
                     (f"{c.source}, rmse {c.rmse_px:.2f}px, conf {c.confidence:.2f}" if c else "; ".join(ax.warnings)[:60] or "-")])
    return header, rows
